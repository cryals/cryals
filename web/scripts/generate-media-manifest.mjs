import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const publicRoot = join(projectRoot, 'public');
const outputFile = join(projectRoot, 'src', 'data', 'media.generated.ts');

const imageExtensions = new Set(['.apng', '.avif', '.bmp', '.gif', '.ico', '.jfif', '.jpeg', '.jpg', '.pjp', '.pjpeg', '.png', '.svg', '.webp']);
const audioExtensions = new Set(['.mp3', '.ogg', '.wav', '.m4a']);

async function listFiles(directory, extensions) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && extensions.has(extname(entry.name).toLowerCase()))
      .map((entry) => join(directory, entry.name))
      .sort((left, right) => left.localeCompare(right));
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') return [];
    throw error;
  }
}

function toPublicUrl(file) {
  const path = relative(publicRoot, file).split(sep).map(encodeURIComponent).join('/');
  return `/${path}`;
}

function trackFromFile(file, links) {
  const filename = file.split(sep).at(-1) ?? '';
  const base = filename.slice(0, -extname(filename).length);
  const [artist, ...titleParts] = base.split(' - ');
  return {
    src: toPublicUrl(file),
    filename,
    artist: titleParts.length ? artist.trim() : 'AL-S selection',
    title: titleParts.length ? titleParts.join(' - ').trim() : base,
    externalUrl: links.get(filename) ?? null,
  };
}

async function readTrackLinks() {
  const links = new Map();
  try {
    const content = await readFile(join(publicRoot, 'music', 'music.txt'), 'utf8');
    for (const line of content.split(/\r?\n/u)) {
      const match = line.match(/^\s*"([^"]+)"\s*-\s*"([^"]+)"\s*$/u);
      if (match) links.set(match[1], match[2]);
    }
  } catch (error) {
    if (!(error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT')) throw error;
  }
  return links;
}

const [avatars, backgrounds, audioFiles, trackLinks] = await Promise.all([
  listFiles(join(publicRoot, 'image', 'avatar'), imageExtensions),
  listFiles(join(publicRoot, 'image', 'background'), imageExtensions),
  listFiles(join(publicRoot, 'music'), audioExtensions),
  readTrackLinks(),
]);

const source = `// Generated by scripts/generate-media-manifest.mjs. Do not edit manually.\n` +
  `export const avatars = ${JSON.stringify(avatars.map(toPublicUrl), null, 2)} as const;\n\n` +
  `export const backgrounds = ${JSON.stringify(backgrounds.map(toPublicUrl), null, 2)} as const;\n\n` +
  `export const tracks = ${JSON.stringify(audioFiles.map((file) => trackFromFile(file, trackLinks)), null, 2)} as const;\n`;

await mkdir(join(projectRoot, 'src', 'data'), { recursive: true });
await writeFile(outputFile, source, 'utf8');
console.log(`Media manifest: ${avatars.length} avatar(s), ${backgrounds.length} background(s), ${audioFiles.length} track(s).`);
